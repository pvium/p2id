// Embed every shipped verification key as base64 so the package works in Node and browsers
// without filesystem access. Run by `yarn build`; src/vk.ts is generated and gitignored.
//
// Ethereum: src/circuits/v<N>.vk (UltraHonk) with its circuit/version.json as v<N>.json.
// Solana:   src/circuits/solana/<env>.v<N>.vk (Sunspot / Groth16) with <env>.v<N>.json from
//           `yarn sync --solana <env>`. Each environment has its own trusted setup, so its own key.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src', 'circuits');
const sha = (b) => '0x' + createHash('sha256').update(b).digest('hex');

const versions = readdirSync(dir)
  .map((f) => /^v(\d+)\.vk$/.exec(f)?.[1])
  .filter(Boolean)
  .map(Number)
  .sort((a, b) => a - b);
if (versions.length === 0) throw new Error('no circuit versions in src/circuits; run yarn sync');
const entries = versions.map((v) => {
  const vk = readFileSync(join(dir, `v${v}.vk`));
  const meta = JSON.parse(readFileSync(join(dir, `v${v}.json`), 'utf8'));
  const vkSha = sha(vk);
  if (meta.circuitVersion !== v) throw new Error(`src/circuits/v${v}.json says circuit version ${meta.circuitVersion}`);
  if (vkSha !== meta.vkSha256) throw new Error(`src/circuits/v${v}.vk hashes to ${vkSha} but v${v}.json says ${meta.vkSha256}`);
  return `  ${v}: { vkBase64: '${vk.toString('base64')}', vkSha256: '${vkSha}' },`;
});
const latest = versions[versions.length - 1];

// Solana keys, checked against what @pvium/p2id-core records as deployed (when it does).
const ENVIRONMENTS = ['production', 'sandbox'];
const solanaDir = join(dir, 'solana');
const recorded = (() => {
  const p = join(root, '..', 'p2id-core', 'src', 'p2id.json');
  if (!existsSync(p)) return null;
  const schemes = JSON.parse(readFileSync(p, 'utf8')).schemes;
  return Object.values(schemes).map((s) => s.solana?.verifiers).filter(Boolean);
})();
const solana = Object.fromEntries(ENVIRONMENTS.map((e) => [e, []]));
const solanaFiles = existsSync(solanaDir) ? readdirSync(solanaDir) : [];
for (const f of solanaFiles) {
  const m = /^(production|sandbox)\.v(\d+)\.vk$/.exec(f);
  if (!m) continue;
  const [, env, vs] = m;
  const v = Number(vs);
  const vk = readFileSync(join(solanaDir, f));
  const meta = JSON.parse(readFileSync(join(solanaDir, `${env}.v${v}.json`), 'utf8'));
  const vkSha = sha(vk);
  if (meta.circuitVersion !== v || meta.environment !== env) throw new Error(`src/circuits/solana/${env}.v${v}.json describes ${meta.environment} v${meta.circuitVersion}`);
  if (vkSha !== meta.vkSha256) throw new Error(`src/circuits/solana/${f} hashes to ${vkSha} but its json says ${meta.vkSha256}`);
  for (const verifiers of recorded ?? []) {
    const deployed = verifiers[env]?.[String(v)];
    if (deployed && deployed.vkHash.toLowerCase() !== vkSha) {
      throw new Error(`src/circuits/solana/${f} hashes to ${vkSha} but @pvium/p2id-core records ${deployed.vkHash} as the deployed ${env} verifier for circuit version ${v}: sync the key the deployment used`);
    }
    if (deployed && meta.zkVerifier && deployed.zkVerifier !== meta.zkVerifier) {
      throw new Error(`src/circuits/solana/${env}.v${v}.json names program ${meta.zkVerifier} but @pvium/p2id-core records ${deployed.zkVerifier}`);
    }
  }
  solana[env].push({ v, vkBase64: vk.toString('base64'), vkSha, zkVerifier: meta.zkVerifier ?? null });
}
const solanaEntries = ENVIRONMENTS.map((env) => {
  const items = solana[env]
    .sort((a, b) => a.v - b.v)
    .map((e) => `    ${e.v}: { vkBase64: '${e.vkBase64}', vkSha256: '${e.vkSha}', zkVerifier: ${e.zkVerifier ? `'${e.zkVerifier}'` : 'null'} },`);
  return `  ${env}: {\n${items.join('\n')}\n  },`;
});

const out = `// GENERATED by scripts/embed-vk.mjs — do not edit.
/** UltraHonk verification keys (keccak / EVM transcript) for every circuit version this release verifies. */
export const CIRCUITS: Readonly<Record<number, { readonly vkBase64: string; readonly vkSha256: string }>> = {
${entries.join('\n')}
};
/** Circuit versions this release verifies, oldest first. */
export const CIRCUIT_VERSIONS: readonly number[] = [${versions.join(', ')}];
/** The newest circuit version: what a current prover produces. */
export const CIRCUIT_VERSION = ${latest};
/** sha256 of the newest version's raw vk bytes. */
export const VK_SHA256 = CIRCUITS[${latest}].vkSha256;

/** A Solana (Sunspot / Groth16) verifying key bundled with this release. */
export interface SolanaCircuit {
  readonly vkBase64: string;
  /** sha256 of the raw vk: the \`vkHash\` of a Solana attestation, and what the factory records. */
  readonly vkSha256: string;
  /** The Solana program built from this key, when deployed. */
  readonly zkVerifier: string | null;
}
/**
 * Solana verifying keys per Pvium environment and circuit version. Each environment has its own
 * trusted setup, so a proof verifies under exactly one of them.
 */
export const SOLANA_CIRCUITS: Readonly<Record<'production' | 'sandbox', Readonly<Record<number, SolanaCircuit>>>> = {
${solanaEntries.join('\n')}
};
`;
writeFileSync(join(root, 'src', 'vk.ts'), out);
const solanaSummary = ENVIRONMENTS.map((e) => `${e}: ${solana[e].length ? solana[e].map((x) => `v${x.v}`).join(', ') : 'none'}`).join('; ');
console.log(`embedded vks for circuit versions ${versions.join(', ')}; Solana ${solanaSummary}`);
