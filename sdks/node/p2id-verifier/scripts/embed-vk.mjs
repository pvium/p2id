// Embed every shipped circuit version's verification key as base64 so the package works in Node
// and browsers without filesystem access. Run by `yarn build`; src/vk.ts is generated and
// gitignored. Each version is src/circuits/v<N>.vk with its circuit/version.json as v<N>.json.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src', 'circuits');
const versions = readdirSync(dir)
  .map((f) => /^v(\d+)\.vk$/.exec(f)?.[1])
  .filter(Boolean)
  .map(Number)
  .sort((a, b) => a - b);
if (versions.length === 0) throw new Error('no circuit versions in src/circuits; run yarn sync');
const entries = versions.map((v) => {
  const vk = readFileSync(join(dir, `v${v}.vk`));
  const meta = JSON.parse(readFileSync(join(dir, `v${v}.json`), 'utf8'));
  const vkSha = '0x' + createHash('sha256').update(vk).digest('hex');
  if (meta.circuitVersion !== v) throw new Error(`src/circuits/v${v}.json says circuit version ${meta.circuitVersion}`);
  if (vkSha !== meta.vkSha256) throw new Error(`src/circuits/v${v}.vk hashes to ${vkSha} but v${v}.json says ${meta.vkSha256}`);
  return `  ${v}: { vkBase64: '${vk.toString('base64')}', vkSha256: '${vkSha}' },`;
});
const latest = versions[versions.length - 1];
const out = `// GENERATED by scripts/embed-vk.mjs — do not edit.
/** UltraHonk verification keys (keccak / EVM transcript) for every circuit version this release verifies. */
export const CIRCUITS: Readonly<Record<number, { readonly vkBase64: string; readonly vkSha256: string }>> = {
${entries.join('\n')}
};
/** Circuit versions this release verifies, oldest first. */
export const CIRCUIT_VERSIONS: readonly number[] = [${versions.join(', ')}];
/** The newest circuit version: what a current prover produces. */
export const CIRCUIT_VERSION = ${latest};
/** sha256 of the newest version's raw vk bytes. */
export const VK_SHA256 = CIRCUITS[${latest}].vkSha256;
`;
writeFileSync(join(root, 'src', 'vk.ts'), out);
console.log(`embedded vks for circuit versions ${versions.join(', ')}`);
