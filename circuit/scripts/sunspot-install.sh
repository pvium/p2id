#!/usr/bin/env bash
# Install the Solana proof toolchain from source, pinned, into <repo>/.tools (gitignored):
#   - Sunspot: Noir ACIR -> gnark Groth16 (BN254) -> Solana verifier program
#   - Reilabs trusted-setup: Groth16 phase-2 ceremony coordinator for gnark circuits
# Nothing is written outside the repo except what `go build` needs, and Go's caches are kept under
# .tools too. Afterwards: `source .tools/env.sh` puts both tools and the matching nargo on PATH.
#
# Prerequisites (not installed here): Go >= 1.24, a Rust toolchain, the Solana CLI (cargo build-sbf),
# and nargo 1.0.0-beta.22, the Noir release Sunspot pins (`noirup -v 1.0.0-beta.22`; the EVM path
# uses a newer nargo, both can be installed side by side as ~/.nargo/bin/nargo-<version>).
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
TOOLS=${P2ID_TOOLS_DIR:-$ROOT/.tools}
SUNSPOT_REPO=https://github.com/reilabs/sunspot.git
SUNSPOT_COMMIT=0a9f7d01070cfb8b34cbfa77e4782e18adacc096 # 2026-10-06, after the HashCloak audit
TRUSTED_SETUP_REPO=https://github.com/reilabs/trusted-setup.git
TRUSTED_SETUP_COMMIT=c31d1ff5970fe3fdcdc896056c7fe53fdbad0a1f # 2026-06-22, gnark 0.14.0 like Sunspot
NOIR_VERSION=1.0.0-beta.22

export GOMODCACHE=$TOOLS/go/mod GOCACHE=$TOOLS/go/cache GOFLAGS=-mod=mod
mkdir -p "$TOOLS" "$GOMODCACHE" "$GOCACHE"

need() { command -v "$1" >/dev/null 2>&1 || { echo "missing: $1 ($2)" >&2; exit 1; }; }
need go "https://go.dev/dl, 1.24 or newer"
need cargo "https://rustup.rs"
need cargo-build-sbf "Solana CLI: https://solana.com/docs/intro/installation"

nargo_bin=""
for candidate in "$HOME/.nargo/bin/nargo-$NOIR_VERSION" "$(command -v nargo || true)"; do
  [ -n "$candidate" ] && [ -x "$candidate" ] || continue
  if "$candidate" --version 2>/dev/null | head -1 | grep -q "nargo version = $NOIR_VERSION"; then
    nargo_bin=$candidate
    break
  fi
done
if [ -z "$nargo_bin" ]; then
  echo "missing: nargo $NOIR_VERSION (noirup -v $NOIR_VERSION; Sunspot reads only this ACIR version)" >&2
  exit 1
fi

checkout() { # name repo commit
  local dir=$TOOLS/$1
  if [ ! -d "$dir/.git" ]; then
    git clone -q "$2" "$dir"
  fi
  git -C "$dir" fetch -q origin "$3" 2>/dev/null || git -C "$dir" fetch -q origin
  git -C "$dir" checkout -q "$3"
  echo "$1 at $(git -C "$dir" rev-parse --short HEAD)"
}

checkout sunspot "$SUNSPOT_REPO" "$SUNSPOT_COMMIT"
# Our own small programs are built inside Sunspot's module so they read its files with the same
# gnark: ccsinfo (size of a constraint system, decides the powers-of-tau file), keyraw (re-encode a
# ceremony key in the raw form Sunspot's verifier generator reads) and sunspotd (the resident
# prover the http-prover runs; its source lives with the service, which also builds it in its image).
for tool in ccsinfo keyraw; do
  mkdir -p "$TOOLS/sunspot/go/cmd/$tool"
  cp "$ROOT/circuit/scripts/sunspot-tools/$tool/main.go" "$TOOLS/sunspot/go/cmd/$tool/main.go"
done
mkdir -p "$TOOLS/sunspot/go/cmd/sunspotd"
cp "$ROOT/http-prover/sunspotd/main.go" "$TOOLS/sunspot/go/cmd/sunspotd/main.go"
(cd "$TOOLS/sunspot/go" && go build -o sunspot ./cmd/sunspot && go build -o ccsinfo ./cmd/ccsinfo \
  && go build -o keyraw ./cmd/keyraw && go build -o sunspotd ./cmd/sunspotd)

checkout trusted-setup "$TRUSTED_SETUP_REPO" "$TRUSTED_SETUP_COMMIT"
# Offline-only entrypoint: the upstream main also wires a gRPC ceremony server whose protobuf code
# needs protoc to generate. The ceremony here is run offline (contributors on their own machines).
mkdir -p "$TOOLS/trusted-setup/cmd/offline"
cat > "$TOOLS/trusted-setup/cmd/offline/main.go" <<'EOF_GO'
// Offline-only build of Reilabs' trusted-setup (no gRPC server, no protoc needed): ptau, init,
// contribute, verify, extract-keys. Generated by circuit/scripts/sunspot-install.sh.
package main

import (
	"context"
	"log"
	"os"
	"path/filepath"

	"github.com/urfave/cli/v3"

	"github.com/reilabs/trusted-setup/offline"
)

func main() {
	app := &cli.Command{
		Name:           filepath.Base(os.Args[0]),
		Usage:          "Groth16 phase-2 trusted setup for gnark circuits (offline mode)",
		DefaultCommand: "help",
		Suggest:        true,
		Commands:       offline.Commands,
	}
	if err := app.Run(context.Background(), os.Args); err != nil {
		log.Fatal(err)
	}
	log.Print("Operation successful")
}
EOF_GO
(cd "$TOOLS/trusted-setup" && go build -o trusted-setup ./cmd/offline)

cat > "$TOOLS/env.sh" <<EOF
# Generated by circuit/scripts/sunspot-install.sh. \`source\` it before the sunspot-*.sh scripts.
export P2ID_TOOLS_DIR="$TOOLS"
export PATH="$TOOLS/sunspot/go:$TOOLS/trusted-setup:\$PATH"
# sunspot deploy builds this crate (the Groth16 verifier program) with the verifying key baked in.
export GNARK_VERIFIER_BIN="$TOOLS/sunspot/gnark-solana/crates/verifier-bin"
# The nargo release whose ACIR Sunspot reads; the EVM path keeps its own newer nargo.
export NARGO_SUNSPOT="$nargo_bin"
export SUNSPOT_BIN="$TOOLS/sunspot/go/sunspot"
export CCSINFO_BIN="$TOOLS/sunspot/go/ccsinfo"
export KEYRAW_BIN="$TOOLS/sunspot/go/keyraw"
# The resident prover for http-prover (SUNSPOTD_BIN in its .env).
export SUNSPOTD_BIN="$TOOLS/sunspot/go/sunspotd"
EOF

echo "sunspot, ccsinfo, keyraw, sunspotd built in $TOOLS/sunspot/go"
echo "trusted-setup built"
echo "nargo $NOIR_VERSION at $nargo_bin"
echo
echo "Next: source $TOOLS/env.sh"
